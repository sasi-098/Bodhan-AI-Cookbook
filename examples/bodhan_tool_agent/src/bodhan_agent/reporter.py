"""Reporting module to write result.md, report.json, trace.jsonl, and organize artifacts."""

from __future__ import annotations

import json
import shutil
import time
from pathlib import Path
from typing import Any


class RunReporter:
    """Writes standardized run outputs: result.md, trace.jsonl, report.json, and artifacts."""

    def __init__(self, out_dir: str | Path):
        self.out_dir = Path(out_dir).resolve()
        self.artifacts_dir = self.out_dir / "artifacts"
        self.trace_file = self.out_dir / "trace.jsonl"
        self.result_file = self.out_dir / "result.md"
        self.report_file = self.out_dir / "report.json"

        # Ensure directories exist
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self.artifacts_dir.mkdir(parents=True, exist_ok=True)

    def log_trace_step(
        self,
        step: int,
        plan: str,
        tool: str,
        arguments: dict[str, Any],
        result_summary: str,
        latency_seconds: float,
        cost_inr: float,
    ) -> None:
        """Append one execution step to trace.jsonl."""
        entry = {
            "step": step,
            "plan": plan,
            "tool": tool,
            "arguments": arguments,
            "result_summary": result_summary,
            "latency_seconds": round(latency_seconds, 2),
            "cost_inr": round(cost_inr, 4),
            "timestamp": time.time(),
        }
        with open(self.trace_file, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

    def collect_artifacts(self, candidate_paths: list[str | Path]) -> list[Path]:
        """Copy generated artifact files into out/artifacts/ and return their new paths."""
        final_artifacts: list[Path] = []
        for p in candidate_paths:
            path = Path(p)
            if path.is_file():
                dest = self.artifacts_dir / path.name
                if path.resolve() != dest.resolve():
                    shutil.copy2(str(path), str(dest))
                final_artifacts.append(dest)
        return final_artifacts

    def write_result_md(
        self,
        task: str,
        status: str,
        final_answer: str,
        assumptions: list[str],
        artifacts: list[Path],
        total_cost: float,
        total_time: float,
        impossible_reason: str | None = None,
    ) -> None:
        """Write human-readable result.md summarizing the run."""
        md_lines = [
            "# Task Execution Result\n",
            f"**Task Instruction:** {task}\n",
            f"**Status:** `{status.upper()}`\n",
            f"**Total Cost:** ₹{total_cost:.4f} INR\n",
            f"**Total Duration:** {total_time:.2f} seconds\n",
            "\n---\n",
        ]

        if status == "impossible_task":
            md_lines.extend([
                "## Honest Failure Explanation\n",
                f"{impossible_reason or final_answer}\n",
                "\n*Notice: In accordance with Bodhan Ground Rules, no fabricated outputs were produced for this unsupported task.*\n",
            ])
        else:
            md_lines.extend([
                "## Final Output & Summary\n",
                f"{final_answer}\n\n",
            ])

            if assumptions:
                md_lines.append("## Assumptions Made\n")
                for a in assumptions:
                    md_lines.append(f"- {a}\n")
                md_lines.append("\n")

            if artifacts:
                md_lines.append("## Generated Artifacts\n")
                for art in artifacts:
                    rel_link = f"artifacts/{art.name}"
                    size_kb = max(1, art.stat().st_size // 1024)
                    md_lines.append(f"- [{art.name}]({rel_link}) ({size_kb} KB)\n")
                md_lines.append("\n")

        md_lines.extend([
            "---\n",
            "*Generated by Bodhan Task Agent. For detailed execution steps, see `trace.jsonl` and `report.json`.*",
        ])

        self.result_file.write_text("".join(md_lines), encoding="utf-8")

    def write_report_json(
        self,
        task: str,
        status: str,
        steps_count: int,
        total_cost: float,
        total_time: float,
        cost_by_model: dict[str, float],
        verification_results: dict[str, Any],
        artifacts: list[Path],
        error: str | None = None,
    ) -> None:
        """Write machine-readable report.json."""
        report = {
            "status": status,
            "task": task,
            "steps_count": steps_count,
            "total_cost_inr": round(total_cost, 4),
            "total_time_seconds": round(total_time, 2),
            "cost_by_model": cost_by_model,
            "verification": verification_results,
            "artifacts": [art.name for art in artifacts],
            "error": error,
            "timestamp": time.time(),
        }
        self.report_file.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
